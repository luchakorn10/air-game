export function artFile(e) {
  let cps = [...e].map(c => c.codePointAt(0).toString(16));
  if (!cps.includes('200d')) cps = cps.filter(c => c !== 'fe0f');
  return `/vendor/twemoji/${cps.join('-')}.svg`;
}
